-- Minimal schema for the multi-tenancy reference.
-- Written for this repo (not a dump of any production schema).

-- Tenants and users are NOT tenant-scoped: no tenant_id_filter column.
CREATE TABLE tenants (
    id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name       VARCHAR(255) NOT NULL UNIQUE,
    created_at TIMESTAMP    NOT NULL DEFAULT now(),
    updated_at TIMESTAMP
);

CREATE TABLE users (
    id    BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    email VARCHAR(255) NOT NULL UNIQUE
);

-- Every tenant-aware table (one that maps a TenantAwareEntity) has the same three columns:
--   id               BIGINT, assigned by the application (@Tsid), so no identity default
--   tenant_id        FK to tenants(id), for relational integrity and joins
--   tenant_id_filter the Hibernate @TenantId discriminator, stored as a string
-- The default '-1' matches CurrentTenantIdentifierResolverImpl.DEFAULT_TENANT_ID: a value that
-- can never belong to a real tenant.
CREATE TABLE tenant_users (
    id               BIGINT       PRIMARY KEY,
    tenant_id        BIGINT       NOT NULL REFERENCES tenants (id),
    tenant_id_filter VARCHAR(255) NOT NULL DEFAULT '-1',
    user_id          BIGINT       NOT NULL REFERENCES users (id),
    created_at       TIMESTAMP,
    updated_at       TIMESTAMP
);

CREATE TABLE projects (
    id               BIGINT       PRIMARY KEY,
    tenant_id        BIGINT       NOT NULL REFERENCES tenants (id),
    tenant_id_filter VARCHAR(255) NOT NULL DEFAULT '-1',
    name             VARCHAR(255) NOT NULL,
    created_at       TIMESTAMP,
    updated_at       TIMESTAMP
);

-- Hibernate adds "tenant_id_filter = ?" to every query on a tenant-aware entity, so the
-- discriminator should lead the index. Without these, tenant-scoped queries scan the whole table.
CREATE INDEX idx_tenant_users_tenant_filter ON tenant_users (tenant_id_filter);
CREATE INDEX idx_projects_tenant_filter_name ON projects (tenant_id_filter, name);
